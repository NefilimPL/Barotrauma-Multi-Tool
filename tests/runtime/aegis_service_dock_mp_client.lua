assert(CLIENT and not Game.IsSingleplayer)
local P='aegis.servo.service.dock';local R={};local c=Character.Controlled
Networking.Receive(P..'.check',function(m)
    R.rack=Entity.FindEntityByID(m.ReadUInt16());R.suit=Entity.FindEntityByID(m.ReadUInt16());R.cell=Entity.FindEntityByID(m.ReadUInt16())
    Timer.Wait(function()
        local ok,detail=pcall(function()
            assert(R.suit.ParentInventory.Owner==R.rack and R.cell.Condition>20,'docked condition not replicated')
            assert(R.suit.Sprite.Origin.X<0 and R.suit.Sprite.Origin.Y<0,'window origin not loaded')
            return 'source='..R.cell.Condition..' nativeWindowOrigin='..R.suit.Sprite.Origin.X..','..R.suit.Sprite.Origin.Y
        end)
        local result=(ok and 'PASS ' or 'FAIL ')..tostring(detail);print('[SERVO DOCK MP CLIENT] '..result)
        File.Write('LocalMods/System-Aegis/servo-service-dock-mp-client.txt',result)
        Hook.Patch(P..'.camera','Barotrauma.GameScreen','Draw',function()
            local cam=Game.GameScreen.Cam;cam.Zoom=2;cam.Position=R.rack.WorldPosition+Vector2(30,20);cam.TargetPos=cam.Position;cam.UpdateTransform(false,true)
        end,Hook.HookMethodType.Before)
        File.Write('LocalMods/System-Aegis/headset-capture.request',(AegisCaptureRoot or 'LocalMods/System-Aegis/')..'servo-service-rack-final.png')
        Timer.Wait(function() Hook.RemovePatch(P..'.camera','Barotrauma.GameScreen','Draw',Hook.HookMethodType.Before) end,1500)
    end,1500)
end)
local hello=Networking.Start(P..'.ready');Networking.Send(hello)
